"""Write PR Wrangler's results to GitHub: labels, one guide comment per PR, an inline
"Start here" comment, and a pinned Review Queue issue.

Deterministic on purpose: ~60 writes through the model would burn the Groq budget and could
come out differently each run. Safe to re-run: comments and the queue issue are found by a
hidden marker and edited in place, and labels are replaced, not stacked.

Conventions (seed/reset.py depends on them): every comment contains <!-- pr-wrangler -->;
every label starts with queue:, lane:, risk:, or deps:; the queue issue has label pr-wrangler:queue.
"""

import json
import os
import re

import httpx
from langchain.tools import ToolRuntime, tool

REPO = "dhanush014/tiny-todo"
MARKER = "<!-- pr-wrangler -->"
QUEUE_LABEL = "pr-wrangler:queue"
QUEUE_DATA_START, QUEUE_DATA_END = "<!-- pr-wrangler-queue ", " -->"
OURS = ("queue:", "lane:", "risk:", "deps:", "pr-wrangler:")

LANE = {
    "quick-win": ("⚡ Quick win", "0e8a16"),
    "review": ("🔍 Needs review", "1d76db"),
    "fix-first": ("🛠️ Fix first", "d93f0b"),
    "blocked": ("⛔ Blocked", "b60205"),
}
RISK_COLOR = {"low": "c2e0c6", "medium": "fbca04", "high": "e11d21"}
SEVERITY = {"bug": "🐛", "risk": "⚠️", "note": "📝"}


# ---------- reading the agent's saved results ----------

def load_results(files: dict) -> tuple[dict, dict, dict]:
    def load(entry):
        content = entry["content"]
        return json.loads(content if isinstance(content, str) else "\n".join(content))

    briefs = {int(p.rsplit("/", 1)[1].split(".")[0]): load(e) for p, e in files.items() if p.startswith("/briefs/")}
    deps = load(files["/deps.json"]) if "/deps.json" in files else {}
    queue = load(files["/queue.json"]) if "/queue.json" in files else {}
    return briefs, deps, queue


# ---------- rendering ----------

def guide_comment(pr: int, brief: dict, dep: dict | None, queue: dict) -> str:
    order = [i["pr"] for i in queue.get("order", [])]
    item = next((i for i in queue.get("order", []) if i["pr"] == pr), None)
    lines = [MARKER]
    if item:
        lane_name = LANE[item["lane"]][0]
        lines.append(f"### 🤠 PR Wrangler · #{order.index(pr) + 1} of {len(order)} in the queue · {lane_name}")
        lines.append(f"_{item['reason']}_\n")
    else:
        lines.append("### 🤠 PR Wrangler\n")
    if brief:
        lines.append(f"**What it does:** {brief['summary']}")
        lines.append(f"**Risk:** {brief['risk']} · {brief['risk_reason']}")
        s = brief["start_here"]
        lines.append(f"**👉 Start here:** `{s['file']}` · `{s['code'].strip()}`  \n{s['why']}")
        if brief["findings"]:
            lines.append("\n**Findings**")
            lines += [f"- {SEVERITY[f['severity']]} **{f['severity']}** `{f['file']}`: {f['issue']}" for f in brief["findings"]]
    if dep and dep.get("flags"):
        lines.append(f"\n**📦 Dependencies:** {', '.join(f'`{f}`' for f in dep['flags'])}  \n{dep['explanation']}  \n➡️ {dep['suggestion']}")
    for c in queue.get("collisions", []):
        if pr in c["prs"]:
            other = ", ".join(f"#{p}" for p in c["prs"] if p != pr)
            lines.append(f"\n**💥 Edits the same lines as {other}** in `{c['file']}`: {c['advice']}")
    for g in queue.get("review_together", []):
        if pr in g["prs"]:
            others = ", ".join(f"#{p}" for p in g["prs"] if p != pr)
            lines.append(f"\n**🤝 Review together with {others}:** {g['why']}")
    for b in queue.get("blocked", []):
        if b["pr"] == pr:
            lines.append(f"\n**⛔ Waits for #{b['waits_for']}:** {b['why']}")
    if brief and brief.get("skim"):
        lines.append("\n<details><summary>Safe to skim</summary>\n\n" + "\n".join(f"- {s}" for s in brief["skim"]) + "\n</details>")
    lines.append("\n<sub>Generated by PR Wrangler. It never approves or merges.</sub>")
    return "\n".join(lines)


def queue_issue(queue: dict, deps: dict, titles: dict) -> str:
    lines = [MARKER, f"## 🤠 Review Queue\n\n**{queue['headline']}**\n", "| # | PR | Lane | Why |", "|---|---|---|---|"]
    for i, item in enumerate(queue["order"], 1):
        lines.append(f"| {i} | #{item['pr']} {titles.get(item['pr'], '')} | {LANE[item['lane']][0]} | {item['reason']} |")
    if queue.get("collisions"):
        lines.append("\n### 💥 Same lines, different PRs")
        lines += [f"- #{' & #'.join(map(str, c['prs']))} in `{c['file']}`: {c['advice']}" for c in queue["collisions"]]
    if queue.get("review_together"):
        lines.append("\n### 🤝 Review together")
        lines += [f"- #{' + #'.join(map(str, g['prs']))}: {g['why']}" for g in queue["review_together"]]
    if queue.get("blocked"):
        lines.append("\n### ⛔ Blocked")
        lines += [f"- #{b['pr']} waits for #{b['waits_for']}: {b['why']}" for b in queue["blocked"]]
    flagged = [v for v in deps.get("prs", []) if v.get("flags")]
    if flagged:
        lines.append("\n### 📦 Dependency flags")
        lines += [f"- #{v['pr']} {', '.join(v['packages'])}: {', '.join(v['flags'])}. {v['suggestion']}" for v in flagged]
    lines.append("\n<sub>Updated by PR Wrangler on every run. It never approves or merges.</sub>")
    # The queue itself, hidden, so other steps (the Slack digest) can read it without a re-run.
    lines.append(f"\n{QUEUE_DATA_START}{json.dumps(queue, separators=(',', ':'))}{QUEUE_DATA_END}")
    return "\n".join(lines)


def labels_for(pr: int, brief: dict | None, dep: dict | None, queue: dict) -> dict[str, str]:
    """label name -> color"""
    out = {}
    order = [i["pr"] for i in queue.get("order", [])]
    if pr in order:
        out[f"queue:{order.index(pr) + 1:02d}"] = "5319e7"
        lane = next(i["lane"] for i in queue["order"] if i["pr"] == pr)
        out[f"lane:{lane}"] = LANE[lane][1]
    if brief:
        out[f"risk:{brief['risk']}"] = RISK_COLOR[brief["risk"]]
    for flag in (dep or {}).get("flags", []):
        out[f"deps:{flag}"] = "e99695"
    return out


# ---------- "Start here": find the line in the diff ----------

HUNK = re.compile(r"^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@")


def locate(patch: str, code: str) -> tuple[int, str] | None:
    """(line, side) of `code` in a unified diff. Removed lines are on the LEFT side."""
    want = code.strip()
    old = new = 0
    fallback = None
    for line in (patch or "").splitlines():
        m = HUNK.match(line)
        if m:
            old, new = int(m.group(1)), int(m.group(2))
            continue
        body = line[1:].strip()
        if line.startswith("+"):
            if body == want:
                return new, "RIGHT"
            if want and want in body and fallback is None:
                fallback = (new, "RIGHT")
            new += 1
        elif line.startswith("-"):
            if body == want:
                return old, "LEFT"
            old += 1
        else:
            if body == want and fallback is None:
                fallback = (new, "RIGHT")
            old += 1
            new += 1
    return fallback


# ---------- GitHub writes ----------

class GitHub:
    def __init__(self):
        self.http = httpx.AsyncClient(
            base_url="https://api.github.com",
            headers={"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}", "Accept": "application/vnd.github+json"},
            timeout=30,
        )

    async def call(self, method, path, **kw):
        r = await self.http.request(method, path, **kw)
        r.raise_for_status()
        return r.json() if r.content else None

    async def ensure_labels(self, wanted: dict[str, str]):
        existing = {l["name"] for l in await self.call("GET", f"/repos/{REPO}/labels", params={"per_page": 100})}
        for name, color in wanted.items():
            if name not in existing:
                await self.call("POST", f"/repos/{REPO}/labels", json={"name": name, "color": color})

    async def set_labels(self, pr: int, ours: list[str]):
        current = [l["name"] for l in await self.call("GET", f"/repos/{REPO}/issues/{pr}/labels")]
        keep = [l for l in current if not l.startswith(OURS)]
        if sorted(keep + ours) != sorted(current):
            await self.call("PUT", f"/repos/{REPO}/issues/{pr}/labels", json={"labels": keep + ours})

    async def upsert_comment(self, number: int, body: str) -> str:
        comments = await self.call("GET", f"/repos/{REPO}/issues/{number}/comments", params={"per_page": 100})
        mine = next((c for c in comments if MARKER in (c["body"] or "")), None)
        if mine is None:
            await self.call("POST", f"/repos/{REPO}/issues/{number}/comments", json={"body": body})
            return "created"
        if mine["body"] != body:
            await self.call("PATCH", f"/repos/{REPO}/issues/comments/{mine['id']}", json={"body": body})
            return "updated"
        return "unchanged"

    async def upsert_start_here(self, pr: int, head_sha: str, files: list[dict], spot: dict) -> str:
        patch = next((f.get("patch") for f in files if f["filename"] == spot["file"]), None)
        where = locate(patch, spot["code"])
        if where is None:
            return "line not found in diff"
        line, side = where
        body = f"{MARKER}\n👉 **Start here.** {spot['why']}"
        existing = [c for c in await self.call("GET", f"/repos/{REPO}/pulls/{pr}/comments", params={"per_page": 100})
                    if MARKER in (c["body"] or "")]
        for c in existing:
            if c["path"] == spot["file"] and c.get("line") == line and c.get("side") == side:
                if c["body"] != body:
                    await self.call("PATCH", f"/repos/{REPO}/pulls/comments/{c['id']}", json={"body": body})
                    return "updated"
                return "unchanged"
            await self.call("DELETE", f"/repos/{REPO}/pulls/comments/{c['id']}")
        await self.call("POST", f"/repos/{REPO}/pulls/{pr}/comments", json={
            "body": body, "commit_id": head_sha, "path": spot["file"], "line": line, "side": side,
        })
        return "created"

    async def upsert_queue_issue(self, body: str) -> int:
        await self.ensure_labels({QUEUE_LABEL: "5319e7"})
        issues = await self.call("GET", f"/repos/{REPO}/issues", params={"labels": QUEUE_LABEL, "state": "open"})
        if issues:
            number = issues[0]["number"]
            if issues[0]["body"] != body:
                await self.call("PATCH", f"/repos/{REPO}/issues/{number}", json={"body": body})
            return number
        issue = await self.call("POST", f"/repos/{REPO}/issues", json={
            "title": "🤠 Review Queue", "body": body, "labels": [QUEUE_LABEL],
        })
        await self.call("POST", "/graphql", json={
            "query": "mutation($id: ID!) { pinIssue(input: {issueId: $id}) { issue { number } } }",
            "variables": {"id": issue["node_id"]},
        })
        return issue["number"]


async def publish(files: dict) -> dict:
    briefs, deps, queue = load_results(files)
    dep_by_pr = {v["pr"]: v for v in deps.get("prs", [])}
    gh = GitHub()
    summary = {"comments": {}, "start_here": {}, "labels": 0}
    async with gh.http:
        prs = {p["number"]: p for p in await gh.call("GET", f"/repos/{REPO}/pulls", params={"state": "open", "per_page": 100})}
        wanted = {n: labels_for(n, briefs.get(n), dep_by_pr.get(n), queue) for n in prs}
        await gh.ensure_labels({name: color for labels in wanted.values() for name, color in labels.items()})
        for n, pr in sorted(prs.items()):
            await gh.set_labels(n, sorted(wanted[n]))
            summary["labels"] += len(wanted[n])
            if n in briefs or n in dep_by_pr:
                summary["comments"][n] = await gh.upsert_comment(n, guide_comment(n, briefs.get(n), dep_by_pr.get(n), queue))
            if n in briefs:
                files_ = await gh.call("GET", f"/repos/{REPO}/pulls/{n}/files")
                summary["start_here"][n] = await gh.upsert_start_here(n, pr["head"]["sha"], files_, briefs[n]["start_here"])
        if queue:
            titles = {n: p["title"] for n, p in prs.items()}
            summary["queue_issue"] = await gh.upsert_queue_issue(queue_issue(queue, deps, titles))
    return summary


@tool
async def publish_to_github(runtime: ToolRuntime) -> str:
    """Publish the saved results to GitHub: labels on every PR, one guide comment per PR,
    an inline "Start here" comment, and the pinned Review Queue issue. Run it last, after the
    queue planner. Takes no arguments. Safe to run again; it edits in place."""
    summary = await publish((runtime.state or {}).get("files") or {})
    misses = {n: s for n, s in summary["start_here"].items() if s not in ("created", "updated", "unchanged")}
    return (
        f"Published: {len(summary['comments'])} guide comments, {summary['labels']} labels, "
        f"{len(summary['start_here']) - len(misses)} Start here comments, queue issue #{summary.get('queue_issue')}."
        + (f" Start here not placed for: {misses}" if misses else "")
    )
